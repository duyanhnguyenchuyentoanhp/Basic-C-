#include <iostream>
using namespace std;

int main() {
    int x,y;
    cin >> x >> y;
    cout << "gtri cua x:\t\t " << "gtri cua y:\t\t " << "bieu thuc\t\t" << "ket qua\t\t" << "\n";
    cout << x << "       \t\t " << y << "        \t\t "  << "    x+y" << "       \t\t" << x+y << "\n"; // 2 tab và \t để thẳng hàng trên
    cout << x << "       \t\t " << y << "        \t\t "  << "    x-y" << "       \t\t" << x-y << "\n";
    cout << x << "       \t\t " << y << "        \t\t "  << "    x*y" << "       \t\t" << x*y << "\n";
    cout << x << "       \t\t " << y << "        \t\t "  << "    x/y" << "       \t\t" << x/y << "\n";
    cout << x << "       \t\t " << y << "        \t\t "  << "    x%y" << "       \t\t" << x%y << "\n";
    return 0;
}
