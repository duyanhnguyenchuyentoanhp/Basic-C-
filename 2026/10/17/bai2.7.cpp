#include <iostream>
using namespace std;

int main() {
    float a,b,c; // để lấy điểm phẩy
    cout << "nhập điểm kiểm tra của bạn:" << "\n";
    cin >> a;
    cout << "nhập điểm giữa kì cùa bạn:" << "\n";
    cin >> b;
    cout << "nhập điểm cuối kì của bạn:" << "\n";
    cin >> c;
    cout << "tổng điểm của bạn là:" << a+b+c;
    return 0;
}
